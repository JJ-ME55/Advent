// Copies the ABIs the site needs out of contracts/out (run `forge build` in contracts/ first).
// Writes src/generated/abis.js. The contract ABIs are never hand-typed; the token is Pons' plain ERC-20, so its
// minimal ABI (Transfer, balanceOf, totalSupply) and the Pons fee escrow's balanceOf are inlined here.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = process.env.CONTRACTS_OUT ?? join(root, "..", "contracts", "out");

function abi(file, name = file) {
  const p = join(out, `${file}.sol`, `${name}.json`);
  if (!existsSync(p)) throw new Error(`Missing ${p}. Build the contracts first: cd contracts && forge build`);
  return JSON.parse(readFileSync(p, "utf8")).abi;
}

// A plain ERC-20, as Pons' factory deploys it: only what the site reads.
export const erc20Abi = [
  { type: "event", name: "Transfer", anonymous: false, inputs: [{ name: "from", type: "address", indexed: true }, { name: "to", type: "address", indexed: true }, { name: "value", type: "uint256", indexed: false }] },
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "account", type: "address" }], outputs: [{ name: "", type: "uint256" }] },
  { type: "function", name: "totalSupply", stateMutability: "view", inputs: [], outputs: [{ name: "", type: "uint256" }] },
];
// Pons' fee escrow: what it holds for a recipient (the splitter), claimable by harvest().
export const escrowAbi = [
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "recipient", type: "address" }], outputs: [{ name: "", type: "uint256" }] },
];

export function writeAbis() {
  const draw = abi("TombolaDraw");
  const splitter = abi("TombolaSplitter");
  const beacon = abi("DrandBeacon");
  // Everything the site reads must be in these ABIs, so a stale contracts/out fails the build here.
  const need = (abiArr, what, names) => {
    for (const n of names) if (!abiArr.some((e) => e.name === n)) throw new Error(`${what} ABI has no ${n}; rebuild the contracts or update the site`);
  };
  need(draw, "TombolaDraw", [
    "potRegular", "potMega", "reserved", "unclaimedTotal", "activeDraw", "getDraw", "drawCount", "solvent", "weightFor",
    "beacon", "keeper", "guardian", "splitter", "COMMIT_DELAY", "ELIGIBLE_AFTER", "FULL_MULTIPLIER_AFTER", "MIN_BALANCE",
    "settle", "rollover", "commit", "Committed", "Settled", "RolledOver", "Cancelled", "Funded",
  ]);
  need(splitter, "TombolaSplitter", ["harvest", "escrow", "draw", "teamFeeWallet", "POT_BPS", "MEGA_BPS", "TEAM_BPS", "Distributed"]);
  need(beacon, "DrandBeacon", ["isValid", "prove", "randomness", "roundTime", "roundAt", "RoundProven"]);
  const dir = join(root, "src", "generated");
  mkdirSync(dir, { recursive: true });
  const body =
    `// Generated by scripts/abis.mjs from contracts/out. Do not edit.\n` +
    `export const drawAbi = ${JSON.stringify(draw)};\n` +
    `export const splitterAbi = ${JSON.stringify(splitter)};\n` +
    `export const beaconAbi = ${JSON.stringify(beacon)};\n` +
    `export const tokenAbi = ${JSON.stringify(erc20Abi)};\n` +
    `export const escrowAbi = ${JSON.stringify(escrowAbi)};\n`;
  writeFileSync(join(dir, "abis.js"), body);
  return { draw: draw.length, splitter: splitter.length, beacon: beacon.length, token: erc20Abi.length, escrow: escrowAbi.length };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) console.log("ABIs written", writeAbis());
