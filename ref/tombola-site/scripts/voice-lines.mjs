// Records every tannoy line as a short mp3 with the site's ElevenLabs voice ("The Classic Showman", the voice JJ
// used for the videos), into public/audio/lines/<hash>.mp3, and writes src/generated/voice.js listing what exists.
// Lines with live placeholders ({pot}, {who}, ...) are skipped: they stay text-only on the page.
//
//   ELEVENLABS_API_KEY=... node scripts/voice-lines.mjs            # records only the lines that have no clip yet
//   ELEVENLABS_API_KEY=... node scripts/voice-lines.mjs --dry      # lists what it would record, no API calls
//   ELEVENLABS_VOICE_ID=... overrides the voice; otherwise the script looks "The Classic Showman" up in the account's
//   voices and then in the shared library (adding it to the account if needed).
//
// The key never goes in a file. Put it in the environment for one command, or in a file named by
// ELEVENLABS_KEY_FILE outside the repository.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { LINES, hashLine, spokenLines } from "../src/lines.js";

const root = fileURLToPath(new URL("..", import.meta.url));
const outDir = join(root, "public", "audio", "lines");
const manifest = join(root, "src", "generated", "voice.js");
const dry = process.argv.includes("--dry");
const VOICE_NAME = process.env.ELEVENLABS_VOICE_NAME || "The Classic Showman";
const MODEL = process.env.ELEVENLABS_MODEL || "eleven_multilingual_v2";
const FORMAT = "mp3_22050_32"; // small: about 4 KB per second

function apiKey() {
  if (process.env.ELEVENLABS_API_KEY) return process.env.ELEVENLABS_API_KEY.trim();
  if (process.env.ELEVENLABS_KEY_FILE) return readFileSync(process.env.ELEVENLABS_KEY_FILE, "utf8").trim();
  return "";
}

async function api(path, key, init = {}) {
  const r = await fetch(`https://api.elevenlabs.io${path}`, { ...init, headers: { "xi-api-key": key, ...(init.headers || {}) } });
  if (!r.ok) throw new Error(`${init.method || "GET"} ${path}: HTTP ${r.status} ${(await r.text()).slice(0, 300)}`);
  return r;
}

async function findVoice(key) {
  if (process.env.ELEVENLABS_VOICE_ID) return process.env.ELEVENLABS_VOICE_ID;
  const mine = await (await api("/v1/voices", key)).json();
  const hit = (mine.voices || []).find((v) => v.name?.toLowerCase() === VOICE_NAME.toLowerCase());
  if (hit) return hit.voice_id;
  // not in the account yet: find it in the shared library and add it
  const q = encodeURIComponent(VOICE_NAME);
  const shared = await (await api(`/v1/shared-voices?search=${q}&page_size=10`, key)).json();
  const s = (shared.voices || []).find((v) => v.name?.toLowerCase() === VOICE_NAME.toLowerCase()) || (shared.voices || [])[0];
  if (!s) throw new Error(`voice "${VOICE_NAME}" not found in the account or the shared library; set ELEVENLABS_VOICE_ID`);
  await api(`/v1/voices/add/${s.public_owner_id}/${s.voice_id}`, key, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ new_name: s.name }) });
  console.log(`added "${s.name}" (${s.voice_id}) from the shared library`);
  return s.voice_id;
}

async function record(key, voiceId, text) {
  const r = await api(`/v1/text-to-speech/${voiceId}?output_format=${FORMAT}`, key, {
    method: "POST",
    headers: { "content-type": "application/json", accept: "audio/mpeg" },
    body: JSON.stringify({ text, model_id: MODEL, voice_settings: { stability: 0.35, similarity_boost: 0.8, style: 0.6, use_speaker_boost: true } }),
  });
  return Buffer.from(await r.arrayBuffer());
}

function writeManifest() {
  const have = existsSync(outDir) ? readdirSync(outDir).filter((f) => f.endsWith(".mp3")).map((f) => f.slice(0, -4)) : [];
  mkdirSync(join(root, "src", "generated"), { recursive: true });
  writeFileSync(manifest, `// Generated by scripts/voice-lines.mjs: the tannoy lines that have a recorded clip in audio/lines/.\nexport const VOICED = new Set(${JSON.stringify(have.sort())});\n`);
  return have.length;
}

const lines = spokenLines(LINES);
mkdirSync(outDir, { recursive: true });
const todo = lines.filter((l) => !existsSync(join(outDir, `${hashLine(l)}.mp3`)));
console.log(`${lines.length} spoken lines, ${lines.length - todo.length} recorded, ${todo.length} to record`);
if (dry) { for (const l of todo) console.log(" -", hashLine(l), l.slice(0, 80)); console.log("manifest lists", writeManifest()); process.exit(0); }
const key = apiKey();
if (!key) { console.error("no ELEVENLABS_API_KEY (or ELEVENLABS_KEY_FILE) in the environment"); process.exit(2); }
const voiceId = await findVoice(key);
console.log("voice", voiceId, "model", MODEL);
let done = 0, failed = 0;
for (const l of todo) {
  const h = hashLine(l);
  try {
    const buf = await record(key, voiceId, l);
    writeFileSync(join(outDir, `${h}.mp3`), buf);
    done++;
    console.log(`ok  ${h} ${(buf.length / 1024).toFixed(0)} KB  ${l.slice(0, 70)}`);
  } catch (e) {
    failed++;
    console.error(`FAIL ${h} ${l.slice(0, 70)}: ${e.message}`);
  }
}
console.log(`recorded ${done}, failed ${failed}, manifest lists ${writeManifest()}`);
process.exit(failed ? 1 : 0);
