// Build step: copies the ABIs the Worker needs from ../contracts/out into src/generated/abis.js.
// The ABIs are never hard-coded (the beacon and draw contract are the audited builds): rebuild the contracts
// (cd contracts && forge build) and this runs again on every `wrangler dev` and `wrangler deploy`.
// The token is Pons' plain ERC-20, so its ABI is the standard one, written here.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = process.env.CONTRACTS_OUT ?? join(here, "..", "..", "contracts", "out");
const read = (file, name) => {
  const p = join(out, file, `${name}.json`);
  if (!existsSync(p)) throw new Error(`Missing ${p}. Build the contracts first: cd contracts && forge build`);
  return JSON.parse(readFileSync(p, "utf8")).abi;
};

/** A plain ERC-20 (what Pons' factory deploys): no hooks, no owner. */
const erc20 = [
  { type: "function", name: "name", stateMutability: "view", inputs: [], outputs: [{ name: "", type: "string" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ name: "", type: "string" }] },
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ name: "", type: "uint8" }] },
  { type: "function", name: "totalSupply", stateMutability: "view", inputs: [], outputs: [{ name: "", type: "uint256" }] },
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "account", type: "address" }], outputs: [{ name: "", type: "uint256" }] },
  { type: "function", name: "allowance", stateMutability: "view", inputs: [{ name: "owner", type: "address" }, { name: "spender", type: "address" }], outputs: [{ name: "", type: "uint256" }] },
  { type: "function", name: "transfer", stateMutability: "nonpayable", inputs: [{ name: "to", type: "address" }, { name: "value", type: "uint256" }], outputs: [{ name: "", type: "bool" }] },
  { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ name: "spender", type: "address" }, { name: "value", type: "uint256" }], outputs: [{ name: "", type: "bool" }] },
  { type: "function", name: "transferFrom", stateMutability: "nonpayable", inputs: [{ name: "from", type: "address" }, { name: "to", type: "address" }, { name: "value", type: "uint256" }], outputs: [{ name: "", type: "bool" }] },
  { type: "event", name: "Transfer", anonymous: false, inputs: [{ name: "from", type: "address", indexed: true }, { name: "to", type: "address", indexed: true }, { name: "value", type: "uint256", indexed: false }] },
  { type: "event", name: "Approval", anonymous: false, inputs: [{ name: "owner", type: "address", indexed: true }, { name: "spender", type: "address", indexed: true }, { name: "value", type: "uint256", indexed: false }] },
];

const abis = {
  draw: read("TombolaDraw.sol", "TombolaDraw"),
  splitter: read("TombolaSplitter.sol", "TombolaSplitter"),
  beacon: read("DrandBeacon.sol", "DrandBeacon"),
  token: erc20,
};

// Fail the build early if something the Worker relies on was renamed in the audit.
const need = {
  draw: ["potRegular", "potMega", "reserved", "activeDraw", "getDraw", "drawCount", "solvent", "beacon", "keeper", "splitter", "weightFor", "COMMIT_DELAY",
    "event:Committed", "event:Settled", "event:RolledOver", "event:Cancelled", "event:PayoutCredited", "event:Funded"],
  splitter: ["harvest", "escrow", "draw", "event:Distributed"],
  beacon: ["roundTime", "roundAt", "randomness", "isValid", "GENESIS", "PERIOD"],
};
for (const [k, names] of Object.entries(need)) {
  for (const n of names) {
    const [type, name] = n.startsWith("event:") ? ["event", n.slice(6)] : ["function", n];
    if (!abis[k].some((x) => x.type === type && x.name === name)) throw new Error(`${k} ABI has no ${type} ${name}: the Worker needs updating`);
  }
}

mkdirSync(join(here, "..", "src", "generated"), { recursive: true });
const file = join(here, "..", "src", "generated", "abis.js");
const text = "// Generated by scripts/abis.mjs from contracts/out. Do not edit.\n" +
  Object.entries(abis).map(([k, v]) => `export const ${k}Abi = ${JSON.stringify(v)};`).join("\n") + "\n";
// write only on change: wrangler dev watches src/ and would otherwise rebuild forever
if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
  writeFileSync(file, text);
  console.log(`abis: wrote src/generated/abis.js from ${out}`);
} else console.log("abis: unchanged");
